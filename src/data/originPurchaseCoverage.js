export function getOriginPurchaseCoverage(fruitId, regionName) {
  return ORIGIN_PURCHASE_COVERAGE.find(
    (entry) => entry.fruitId === fruitId && entry.region === regionName,
  );
}

export function getVerifiedOriginPurchasePlaces(fruitId, regionName) {
  const coverage = getOriginPurchaseCoverage(fruitId, regionName);
  return coverage?.status === "verified" ? coverage.places : [];
}
